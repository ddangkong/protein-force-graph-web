_compiled = [(tag, cat, [re.compile(p, re.I) for p in pats]) for tag, cat, pats in TAG_RULES]


def tag_text(text):
    """Return list of (tag, category) matched in text."""
    if not text:
        return []
    found = []
    for tag, cat, pats in _compiled:
        if any(p.search(text) for p in pats):
            found.append((tag, cat))
    return found


